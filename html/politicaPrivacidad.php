    <section class="privacy-section" id="menores" aria-labelledby="titulo-menores">
      <h2 id="titulo-menores">
        <span class="section-num" aria-hidden="true">8</span>
        Menores de edad
      </h2>
      <p>
        Los servicios de Classia están dirigidos a personas mayores de
        <strong>18 años</strong>. No recopilamos intencionalmente datos de
        menores de edad sin el consentimiento verificable de su padre, madre o
        representante legal, conforme a lo establecido en la Ley 17.823
        (Código de la Niñez y la Adolescencia) y el artículo 12 de la
        Ley 18.331.
      </p>
      <p>
        Si detectamos que hemos recabado datos de un menor sin el
        consentimiento requerido, procederemos a su eliminación inmediata.
        Si sos padre, madre o tutor y tenés conocimiento de que un menor
        registró datos en nuestra plataforma, contactá a
        <a href="mailto:privacidad@classia.uy">privacidad@classia.uy</a>.
      </p>
    </section>

    <section class="privacy-section" id="derechos" aria-labelledby="titulo-derechos">
      <h2 id="titulo-derechos">
        <span class="section-num" aria-hidden="true">9</span>
        Tus derechos como titular de datos
      </h2>
      <p>
        La Ley 18.331 te reconoce los siguientes derechos respecto al
        tratamiento de tus datos personales, los cuales podés ejercer de forma
        gratuita:
      </p>

      <div class="rights-grid">
        <article class="right-card">
          <span class="right-icon" aria-hidden="true"></span>
          <h3>Derecho de acceso</h3>
          <p>
            Solicitar información sobre qué datos personales tuyos son tratados
            por Classia, su origen y las finalidades del tratamiento (art. 14,
            Ley 18.331).
          </p>
        </article>

        <article class="right-card">
          <span class="right-icon" aria-hidden="true"></span>
          <h3>Derecho de rectificación</h3>
          <p>
            Corregir tus datos cuando sean inexactos, incompletos,
            desactualizados o engañosos (art. 15, Ley 18.331).
          </p>
        </article>

        <article class="right-card">
          <span class="right-icon" aria-hidden="true"></span>
          <h3>Derecho de supresión</h3>
          <p>
            Solicitar la eliminación de tus datos cuando ya no sean necesarios
            o cuando hayas revocado el consentimiento, siempre que no existan
            obligaciones legales de conservación (art. 16, Ley 18.331).
          </p>
        </article>

        <article class="right-card">
          <span class="right-icon" aria-hidden="true"></span>
          <h3>Derecho de impugnación</h3>
          <p>
            Oponerte al tratamiento de tus datos para determinadas finalidades,
            en especial para fines de publicidad directa o elaboración de
            perfiles (art. 16, Ley 18.331).
          </p>
        </article>

        <article class="right-card">
          <span class="right-icon" aria-hidden="true"></span>
          <h3>Habeas Data</h3>
          <p>
            Acudir ante la URCDP o los tribunales competentes para proteger tus
            datos y exigir su corrección, eliminación o bloqueo ante un
            tratamiento contrario a la ley (art. 37 y ss., Ley 18.331).
          </p>
        </article>

        <article class="right-card">
          <span class="right-icon" aria-hidden="true"></span>
          <h3>Derecho a no ser objeto de decisiones automatizadas</h3>
          <p>
            No ser objeto de decisiones con efectos jurídicos significativos
            basadas exclusivamente en el tratamiento automatizado de tus datos,
            sin intervención humana (art. 17, Ley 18.331).
          </p>
        </article>
      </div>

      <div class="legal-highlight">
        <p>
          <strong>Plazos de respuesta:</strong> Classia responderá a tu
          solicitud en un plazo máximo de <strong>5 días hábiles</strong> para
          acusar recibo, y resolverá la solicitud en los plazos establecidos
          por el artículo 14 y concordantes de la Ley 18.331 (generalmente
          hasta 30 días hábiles para la resolución definitiva).
        </p>
      </div>
    </section>

