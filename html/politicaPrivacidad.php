    <section class="privacy-section" id="conservacion" aria-labelledby="titulo-conservacion">
      <h2 id="titulo-conservacion">
        <span class="section-num" aria-hidden="true">4</span>
        Conservación de los datos
      </h2>
      <p>
        Los datos personales se conservarán durante el tiempo estrictamente
        necesario para cumplir las finalidades para las que fueron recabados,
        conforme al principio de temporalidad (art. 8, literal d, Ley 18.331):
      </p>
      <ul>
        <li>
          <strong>Cuenta activa:</strong> Mientras mantengas tu cuenta activa
          en Classia o hasta que solicites su eliminación.
        </li>
        <li>
          <strong>Tras la baja de la cuenta:</strong> Los datos se conservarán
          bloqueados por un período de hasta <strong>5 años</strong> para
          atender posibles reclamaciones legales, obligaciones fiscales u otras
          exigencias normativas, y luego serán suprimidos de forma segura.
        </li>
        <li>
          <strong>Datos de transacciones:</strong> Conforme a la normativa
          tributaria uruguaya y las disposiciones del Banco Central del Uruguay
          (BCU), se conservarán por el plazo legalmente establecido.
        </li>
        <li>
          <strong>Datos de navegación y logs:</strong> Se eliminan de forma
          automática a los 12 meses.
        </li>
      </ul>
    </section>

    <section class="privacy-section" id="transferencias" aria-labelledby="titulo-transferencias">
      <h2 id="titulo-transferencias">
        <span class="section-num" aria-hidden="true">5</span>
        Transferencias y destinatarios
      </h2>
      <p>
        Classia no vende, alquila ni cede tus datos personales a terceros con
        fines comerciales propios de esos terceros. Los datos podrán ser
        comunicados a:
      </p>
      <ul>
        <li>
          <strong>Proveedores de servicios técnicos:</strong> Empresas que
          prestan servicios de hosting, almacenamiento en la nube, pasarela de
          pagos y análisis de plataforma, actuando como encargados del
          tratamiento bajo instrucciones de Classia y con obligaciones de
          confidencialidad equivalentes.
        </li>
        <li>
          <strong>Autoridades competentes:</strong> Cuando la ley lo exija o
          en el marco de procedimientos judiciales o administrativos.
        </li>
        <li>
          <strong>Otros usuarios de la plataforma:</strong> Únicamente la
          información de perfil que el propio usuario elija hacer pública
          (nombre visible, descripción profesional, valoraciones recibidas).
        </li>
      </ul>

      <h3>5.1 Transferencias internacionales</h3>
      <p>
        En caso de que algún proveedor técnico procese datos fuera del
        territorio uruguayo, Classia adoptará las garantías adecuadas conforme
        al artículo 23 de la Ley 18.331, asegurándose de que el país destino
        cuente con un nivel de protección adecuado reconocido por la URCDP, o
        que existan garantías contractuales suficientes (cláusulas tipo,
        acuerdos de encargado de tratamiento, etc.).
      </p>
    </section>

    <section class="privacy-section" id="seguridad" aria-labelledby="titulo-seguridad">
      <h2 id="titulo-seguridad">
        <span class="section-num" aria-hidden="true">6</span>
        Medidas de seguridad
      </h2>
      <p>
        Aplicamos medidas técnicas y organizativas apropiadas para proteger
        tus datos personales contra el acceso no autorizado, la pérdida, la
        alteración o la divulgación indebida, conforme al artículo 10 de la
        Ley 18.331 y el Decreto 414/009:
      </p>
      <ul>
        <li>Cifrado de contraseñas con algoritmos de hash seguros (bcrypt).</li>
        <li>Transmisión de datos bajo protocolo HTTPS/TLS.</li>
        <li>Controles de acceso basados en roles (RBAC) para el personal interno.</li>
        <li>Copias de seguridad periódicas con almacenamiento cifrado.</li>
        <li>Registro de auditoría de accesos y operaciones sensibles.</li>
        <li>Revisiones periódicas de seguridad y gestión de vulnerabilidades.</li>
      </ul>
      <p>
        Ante una brecha de seguridad que suponga un riesgo para tus derechos,
        Classia notificará a la URCDP y a los titulares afectados en los plazos
        establecidos por la normativa vigente.
      </p>
    </section>

